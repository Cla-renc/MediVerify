class Command(BaseCommand):
    help = 'Seed bilingual sample medicine information records for pharmacist review.'

    def handle(self, *args, **options):
        for row in SAMPLE_MEDICINES:
            (generic, brands, uses_en, uses_sw, usual_en, usual_sw, effects_en, effects_sw,
             warnings_en, warnings_sw, storage_en, storage_sw, doctor_en, doctor_sw) = row
            MedicineInfo.objects.get_or_create(
                generic_name=generic,
                defaults={
                    'brand_names': brands,
                    'uses_en': uses_en,
                    'uses_sw': uses_sw,
                    'usual_use_en': usual_en,
                    'usual_use_sw': usual_sw,
                    'side_effects_en': effects_en,
                    'side_effects_sw': effects_sw,
                    'warnings_en': warnings_en,
                    'warnings_sw': warnings_sw,
                    'storage_en': storage_en,
                    'storage_sw': storage_sw,
                    'see_doctor_en': doctor_en,
                    'see_doctor_sw': doctor_sw,
                    'source': 'SAMPLE - must be reviewed by a pharmacist',
                    'reviewed_by': None,
                    'reviewed_date': None,
                    'is_sample': True,
                },
            )
        self.stdout.write(self.style.SUCCESS(
            f'Seeded {len(SAMPLE_MEDICINES)} bilingual SAMPLE medicine records; pharmacist review is required.'
        ))
